class Canvas:
    def __init__(self, w, h, bg=(255,255,255)):
        self.w, self.h = w, h
        self.buf = bytearray()
        px = bytes(bg)
        for _ in range(w*h):
            self.buf += px
    def px(self, x, y, c):
        x, y = int(x), int(y)
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y*self.w + x)*3
            self.buf[i:i+3] = bytes(c)
    def dot(self, x, y, c, r=1):
        for dy in range(-r, r+1):
            for dx in range(-r, r+1):
                self.px(x+dx, y+dy, c)
    def line(self, x0, y0, x1, y1, c, w=1):
        x0,y0,x1,y1 = int(x0),int(y0),int(x1),int(y1)
        dx, dy = abs(x1-x0), abs(y1-y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx - dy
        while True:
            if w <= 1:
                self.px(x0, y0, c)
            else:
                self.dot(x0, y0, c, w//2)
            if x0 == x1 and y0 == y1: break
            e2 = err*2
            if e2 > -dy: err -= dy; x0 += sx
            if e2 < dx:  err += dx; y0 += sy
    def rect_fill(self, x0, y0, x1, y1, c):
        for y in range(int(y0), int(y1)+1):
            for x in range(int(x0), int(x1)+1):
                self.px(x, y, c)
    def text(self, x, y, s, c=(40,40,40), scale=1):
        cx = x
        for ch in s.upper():
            g = FONT.get(ch, FONT[' '])
            for r in range(7):
                for col in range(5):
                    if g[r][col] == '1':
                        for sy in range(scale):
                            for sx in range(scale):
                                self.px(cx+col*scale+sx, y+r*scale+sy, c)
            cx += 6*scale
    def tw(self, s, scale=1):
        return len(s)*6*scale

    def png(self, path):
        raw = b''
        for y in range(self.h):
            raw += b'\x00' + bytes(self.buf[y*self.w*3:(y+1)*self.w*3])
        def chunk(t, d):
            c = struct.pack('>I', len(d)) + t + d
            return c + struct.pack('>I', zlib.crc32(t+d) & 0xffffffff)
        ihdr = struct.pack('>IIBBBBB', self.w, self.h, 8, 2, 0, 0, 0)
        data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', ihdr) + chunk(b'IDAT', zlib.compress(raw, 6)) + chunk(b'IEND', b'')
        open(path,'wb').write(data)